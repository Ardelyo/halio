"""Collect the real app outputs the video shows (video/assets/shots/*.json) into video/src/data.js.

    python video/tools/make_data.py
"""

from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SHOTS = ROOT / "assets" / "shots"


def load(name: str) -> dict | None:
    p = SHOTS / name
    return json.loads(p.read_text(encoding="utf-8")) if p.exists() else None


def main() -> None:
    bansos, abstain, cov = load("result-bansos.json"), load("result-abstain.json"), load("coverage.json")
    data = {
        "bansos": {k: bansos[k] for k in ("status", "voice_script", "match", "claim")} if bansos else None,
        "abstain": {k: abstain[k] for k in ("status", "voice_script", "claim")} if abstain else None,
        "coverage": {"sources_total": cov["sources_total"], "hidup": cov["counts"]["hidup"],
                     "generated": cov["generated"]} if cov else None,
    }
    (ROOT / "src" / "data.js").write_text(
        "// Generated by video/tools/make_data.py from real app output. Do not edit by hand.\n"
        f"window.DATA = {json.dumps(data, ensure_ascii=False, indent=1)};\n", encoding="utf-8")
    print("data.js written:", {k: bool(v) for k, v in data.items()})


if __name__ == "__main__":
    main()
